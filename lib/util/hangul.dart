/// 한글 자모 분해 검색 키.
///
/// 완성형 음절(가~힣)을 호환 자모(초성/중성/종성)로 분해하고, 복합 자모
/// (ㅘ, ㄺ 등)는 낱자로 쪼갠다. 이렇게 만든 키끼리 `contains`로 비교하면
/// 타이핑 조합 중간 상태도 부분 일치로 걸린다.
///
/// 예) "공과금" → "ㄱㅗㅇㄱㅗㅏㄱㅡㅁ"
///   - "ㄱ" → "ㄱ"                (prefix ✓)
///   - "공" → "ㄱㅗㅇ"            (prefix ✓)
///   - "공ㄱ" → "ㄱㅗㅇㄱ"        (prefix ✓)
///   - "공과" → "ㄱㅗㅇㄱㅗㅏ"    (prefix ✓)
///   - "공과그" → "ㄱㅗㅇㄱㅗㅏㄱㅡ" (prefix ✓)
library;

const _cho = [
  'ㄱ', 'ㄲ', 'ㄴ', 'ㄷ', 'ㄸ', 'ㄹ', 'ㅁ', 'ㅂ', 'ㅃ', 'ㅅ',
  'ㅆ', 'ㅇ', 'ㅈ', 'ㅉ', 'ㅊ', 'ㅋ', 'ㅌ', 'ㅍ', 'ㅎ',
];

const _jung = [
  'ㅏ', 'ㅐ', 'ㅑ', 'ㅒ', 'ㅓ', 'ㅔ', 'ㅕ', 'ㅖ', 'ㅗ', 'ㅘ',
  'ㅙ', 'ㅚ', 'ㅛ', 'ㅜ', 'ㅝ', 'ㅞ', 'ㅟ', 'ㅠ', 'ㅡ', 'ㅢ', 'ㅣ',
];

const _jong = [
  '', 'ㄱ', 'ㄲ', 'ㄳ', 'ㄴ', 'ㄵ', 'ㄶ', 'ㄷ', 'ㄹ', 'ㄺ',
  'ㄻ', 'ㄼ', 'ㄽ', 'ㄾ', 'ㄿ', 'ㅀ', 'ㅁ', 'ㅂ', 'ㅄ', 'ㅅ',
  'ㅆ', 'ㅇ', 'ㅈ', 'ㅊ', 'ㅋ', 'ㅌ', 'ㅍ', 'ㅎ',
];

/// 복합 자모 → 낱자. (음절에서 나온 것과 낱개로 입력된 것 모두 통일)
const _split = {
  'ㅘ': 'ㅗㅏ', 'ㅙ': 'ㅗㅐ', 'ㅚ': 'ㅗㅣ', 'ㅝ': 'ㅜㅓ',
  'ㅞ': 'ㅜㅔ', 'ㅟ': 'ㅜㅣ', 'ㅢ': 'ㅡㅣ',
  'ㄳ': 'ㄱㅅ', 'ㄵ': 'ㄴㅈ', 'ㄶ': 'ㄴㅎ', 'ㄺ': 'ㄹㄱ',
  'ㄻ': 'ㄹㅁ', 'ㄼ': 'ㄹㅂ', 'ㄽ': 'ㄹㅅ', 'ㄾ': 'ㄹㅌ',
  'ㄿ': 'ㄹㅍ', 'ㅀ': 'ㄹㅎ', 'ㅄ': 'ㅂㅅ',
};

/// 자모 분해 검색 키를 만든다.
String jamoKey(String s) {
  final b = StringBuffer();
  for (final rune in s.runes) {
    if (rune >= 0xAC00 && rune <= 0xD7A3) {
      final i = rune - 0xAC00;
      b.write(_cho[i ~/ 588]);
      b.write(_jung[(i % 588) ~/ 28]);
      b.write(_jong[i % 28]);
    } else {
      b.writeCharCode(rune);
    }
  }
  var out = b.toString();
  _split.forEach((k, v) => out = out.replaceAll(k, v));
  return out.toLowerCase();
}
